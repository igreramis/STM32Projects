    const pending = { device_id: 'stm32g0b1-01', release_id: '0.5.0', request_id: crypto.randomUUID(), stage: 'arm_pending' } as const
    sessionStorage.setItem('test-live', JSON.stringify(pending))
    const data = snapshot(), api = testApi(data)
    vi.mocked(api.armStatus).mockRejectedValue(new ApiError('arm_not_found', 404))
    render(<Console runtime={runtime(api)} />)
    await screen.findByText('running')
