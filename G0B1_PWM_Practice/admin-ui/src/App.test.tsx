import { act, fireEvent, render, screen, waitFor } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { describe, expect, it, vi } from 'vitest'
import { Console, UploadDialog } from './App'
import { ApiError } from './api'
import { createRuntime } from './auth'
import { binaryFile, runtime, snapshot, testApi } from './test/fixtures'

describe('console components', () => {
  it('shows offline independently of running state, and disabled navigation', async () => {
    const data = snapshot()
    data.devices[1].last_seen = new Date(Date.now() - 40000).toISOString()
    render(<Console runtime={runtime(testApi(data))} />)
    expect(await screen.findByText('running')).toBeInTheDocument()
    expect(screen.getByText('Offline')).toBeInTheDocument()
    expect(screen.getByText('1 offline')).toBeInTheDocument()
    expect(screen.getByRole('button', { name: /Onboarding/ })).toBeDisabled()
    expect(screen.getByRole('button', { name: /Telemetry/ })).toBeDisabled()
    await userEvent.selectOptions(screen.getByLabelText('Approved release'), '0.5.0')
    expect(screen.getByRole('button', { name: 'Review deploy' })).toBeDisabled()
    expect(screen.getByText(/State and firmware are last known/)).toBeInTheDocument()
  })
  it('requires release selection and confirmation before any real deployment', async () => {
    const api = testApi()
    render(<Console runtime={runtime(api)} />)
    await screen.findByText('running')
    expect(screen.getByRole('button', { name: 'Review deploy' })).toBeDisabled()
    await userEvent.selectOptions(screen.getByLabelText('Approved release'), '0.5.0')
    await userEvent.click(screen.getByRole('button', { name: 'Review deploy' }))
    expect(screen.getByRole('dialog', { name: 'Confirm deployment' })).toBeVisible()
    expect(api.deploy).not.toHaveBeenCalled()
    await userEvent.click(screen.getByRole('button', { name: 'Cancel' }))
    expect(api.deploy).not.toHaveBeenCalled()
    await userEvent.click(screen.getByRole('button', { name: 'Review deploy' }))
    await userEvent.click(screen.getByRole('button', { name: 'Confirm and send' }))
    await waitFor(() => expect(api.deploy).toHaveBeenCalledTimes(1))
    expect(vi.mocked(api.deploy).mock.calls[0][0]).toMatchObject({ device_id: 'stm32g0b1-01', release_id: '0.5.0' })
  })
  it('retains retry identity through component failure and explicit retry confirmation', async () => {
    const api = testApi()
    vi.mocked(api.deploy).mockRejectedValueOnce(new ApiError('network'))
    render(<Console runtime={runtime(api)} />)
    await screen.findByText('running')
    await userEvent.selectOptions(screen.getByLabelText('Approved release'), '0.5.0')
    await userEvent.click(screen.getByRole('button', { name: 'Review deploy' }))
    await userEvent.click(screen.getByRole('button', { name: 'Confirm and send' }))
    await screen.findByText('Deployment response uncertain')
    expect(screen.getByLabelText('Approved release')).toBeDisabled()
    const first = vi.mocked(api.deploy).mock.calls[0][0]
    await userEvent.click(screen.getByRole('button', { name: 'Review retry' }))
    expect(api.deploy).toHaveBeenCalledTimes(1)
    await userEvent.click(screen.getByRole('button', { name: 'Confirm and send' }))
    await waitFor(() => expect(api.deploy).toHaveBeenCalledTimes(2))
    expect(vi.mocked(api.deploy).mock.calls[1][0]).toEqual(first)
  })
  it('does not deploy to the gateway', async () => {
    render(<Console runtime={runtime()} />)
    await screen.findByText('running')
    await userEvent.click(screen.getByRole('button', { name: /pi-lab-01.*Gateway/ }))
    await userEvent.selectOptions(screen.getByLabelText('Approved release'), '0.5.0')
    expect(screen.getByRole('button', { name: 'Review deploy' })).toBeDisabled()
    expect(screen.getByText('Select the subdevice to deploy firmware.')).toBeVisible()
  })
  it('shows conspicuous demo labels and simulates deploy without network', async () => {
    const app = await createRuntime('?demo=1')
    render(<Console runtime={app} />)
    await screen.findByText('ready')
    expect(screen.getByText('DEMO MODE')).toBeInTheDocument()
    await userEvent.selectOptions(screen.getByLabelText('Approved release'), '0.5.0')
    await waitFor(() => expect(screen.getByRole('button', { name: 'Simulate deploy' })).toBeEnabled())
    await userEvent.click(screen.getByRole('button', { name: 'Simulate deploy' }))
    await userEvent.click(screen.getByRole('button', { name: 'Confirm simulation' }))
    await screen.findByText('Simulated deployment created. No command was sent.')
    expect(fetch).not.toHaveBeenCalled()
  })
  it('polls at five seconds and aborts/cleans up on unmount', async () => {
    vi.useFakeTimers()
    const api = testApi()
    const view = render(<Console runtime={runtime(api)} />)
    await act(async () => { await Promise.resolve() })
    expect(api.snapshot).toHaveBeenCalledTimes(1)
    await act(async () => { await vi.advanceTimersByTimeAsync(5000) })
    expect(api.snapshot).toHaveBeenCalledTimes(2)
    const signal = vi.mocked(api.snapshot).mock.calls[1][0]
    view.unmount()
    expect(signal.aborted).toBe(true)
    await vi.advanceTimersByTimeAsync(15000)
    expect(api.snapshot).toHaveBeenCalledTimes(2)
    expect(vi.getTimerCount()).toBe(0)
  })
  it('disables confirmation if observations age out while the modal is open', async () => {
    vi.useFakeTimers()
    const api = testApi()
    render(<Console runtime={runtime(api)} />)
    await act(async () => { await Promise.resolve() })
    fireEvent.change(screen.getByLabelText('Approved release'), { target: { value: '0.5.0' } })
    fireEvent.click(screen.getByRole('button', { name: 'Review deploy' }))
    await act(async () => { await vi.advanceTimersByTimeAsync(36000) })
    expect(screen.getByRole('button', { name: 'Confirm and send' })).toBeDisabled()
    expect(api.deploy).not.toHaveBeenCalled()
  })
  it('sanitizes errors and recovers polling without exposing server details', async () => {
    const api = testApi()
    vi.mocked(api.snapshot).mockRejectedValueOnce(new Error('https://private.example/?token=secret'))
    render(<Console runtime={runtime(api)} />)
    expect(await screen.findByRole('alert')).not.toHaveTextContent('private.example')
    await userEvent.click(screen.getByRole('button', { name: 'Refresh' }))
    await screen.findByText('running')
    expect(screen.queryByRole('alert')).not.toBeInTheDocument()
  })
  it('locks mutations when an access session expires', async () => {
    const api = testApi()
    vi.mocked(api.snapshot).mockRejectedValue(new ApiError('unauthorized', 401))
    render(<Console runtime={runtime(api)} />)
    await screen.findByText('Session expired. Actions are locked.')
    expect(screen.getByRole('button', { name: 'Upload firmware' })).toBeDisabled()
    expect(screen.getByRole('button', { name: 'Sign in again' })).toBeEnabled()
  })
  it('approves an uploaded release without deploying it', async () => {
    const api = testApi()
    render(<Console runtime={runtime(api)} />)
    await screen.findByText('running')
    await userEvent.click(screen.getByRole('button', { name: 'Approve' }))
    await waitFor(() => expect(api.approve).toHaveBeenCalledTimes(1))
    expect(vi.mocked(api.approve).mock.calls[0][0]).toBe('0.6.0')
    expect(api.deploy).not.toHaveBeenCalled()
    await screen.findByText('Release integrity validated and approved.')
  })
})

describe('upload component', () => {
  it('submits the exact version, filename and encoded binary after local checks', async () => {
    const upload = vi.fn(async () => {})
    render(<UploadDialog demo={false} onClose={() => {}} onUpload={upload} />)
    await userEvent.type(screen.getByLabelText('Release version'), '0.5.0')
    await userEvent.upload(screen.getByLabelText('Firmware binary'), binaryFile())
    await userEvent.click(screen.getByRole('button', { name: 'Upload binary' }))
    await waitFor(() => expect(upload).toHaveBeenCalledTimes(1))
    const body = vi.mocked(upload).mock.calls[0] as unknown as [{ version: string; filename: string; content_base64: string }]
    expect(body[0]).toMatchObject({ version: '0.5.0', filename: 'firmware.bin' })
    expect(atob(body[0].content_base64)).toContain('firmware=0.5.0\0')
    expect(fetch).not.toHaveBeenCalled()
  })
  it('rejects missing files and oversize binaries before sending', async () => {
    const upload = vi.fn(async () => {})
    render(<UploadDialog demo={false} onClose={() => {}} onUpload={upload} />)
    await userEvent.type(screen.getByLabelText('Release version'), '0.5.0')
    await userEvent.click(screen.getByRole('button', { name: 'Upload binary' }))
    expect(screen.getByRole('alert')).toHaveTextContent('Choose a firmware binary')
    await userEvent.upload(screen.getByLabelText('Firmware binary'), new File([new Uint8Array(20481)], 'firmware.bin'))
    await userEvent.click(screen.getByRole('button', { name: 'Upload binary' }))
    expect(screen.getByRole('alert')).toHaveTextContent('20 KiB')
    expect(upload).not.toHaveBeenCalled()
  })
})